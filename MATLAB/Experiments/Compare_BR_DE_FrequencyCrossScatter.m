%% Compare modal-frequency clouds from the BR and DE campaigns
%
% The Porto Alegre (BR) raw measurements are processed with the original
% Porto Alegre estimator.  The Hannover (DE) observations are loaded from
% the matched Porto-style analysis.  The resulting six pairwise plots
% compare within-campaign modal-frequency dependence; measurement numbers
% are not paired across campaigns because the campaigns are independent.

clear;
clc;
close all;

%% -------------------- PATHS --------------------
scriptFolder = fileparts(mfilename("fullpath"));
matlabRoot = fileparts(scriptFolder);
addpath(genpath(fullfile(matlabRoot, "Functions")));

portoDataFolder = fullfile( ...
    scriptFolder, ...
    "Porto-Alegre", ...
    "2025-11-Eurodyn-BMU-4DOF", ...
    "processing-test");

hannoverCampaignFolder = fullfile( ...
    scriptFolder, ...
    "Hammer-Test", ...
    "HT_26_07_29_Post_Experiment_Complete_100_Usable_Merged_" + ...
    "2026-07-29-16-31-36");
hannoverMeasurementsFile = fullfile( ...
    hannoverCampaignFolder, ...
    "Analysis_PortoAlegre_Method", ...
    "measurements.txt");

outputFolder = fullfile( ...
    scriptFolder, ...
    "Campaign-Comparison_BR_DE");
brFrequencyCacheFile = fullfile( ...
    outputFolder, "BR_frequencies_porto_style.csv");
forceReprocessBR = false;

if ~isfolder(portoDataFolder)
    error("Porto Alegre raw-data folder not found:\n%s", portoDataFolder);
end

if ~isfile(hannoverMeasurementsFile)
    error("Hannover Porto-style observations not found:\n%s", ...
        hannoverMeasurementsFile);
end

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

%% -------------------- PORTO ALEGRE OBSERVATIONS --------------------
numberOfRuns = 100;
numberOfModes = 4;
frequencyBR = nan(numberOfRuns, numberOfModes);

if ~forceReprocessBR && isfile(brFrequencyCacheFile)
    cachedBR = readmatrix(brFrequencyCacheFile);

    if size(cachedBR, 1) ~= numberOfRuns || ...
            size(cachedBR, 2) ~= 1 + numberOfModes || ...
            any(cachedBR(:, 1) ~= (1:numberOfRuns).', "all") || ...
            any(~isfinite(cachedBR(:, 2:end)), "all")
        error("The cached Porto Alegre frequency file is invalid:\n%s", ...
            brFrequencyCacheFile);
    end

    frequencyBR = cachedBR(:, 2:end);
    fprintf("Loaded cached Porto Alegre observations:\n  %s\n", ...
        brFrequencyCacheFile);
else
    fprintf("Processing Porto Alegre measurements with the reference method:\n");

    for iRun = 1:numberOfRuns
        fprintf("  BR %3d/%3d\n", iRun, numberOfRuns);
        [time, acceleration] = ...
            ReadPortoAlegreMeasurement(portoDataFolder, iRun);
        result = EstimateModalParametersPortoAlegre( ...
            time, acceleration, ...
            "ComputeDamping", false, ...
            "MakePlots", false);

        if result.numberOfPeaks ~= numberOfModes
            error([ ...
                "BR realization %d produced %d peaks; exactly %d were " ...
                "expected from the Porto Alegre reference campaign."], ...
                iRun, result.numberOfPeaks, numberOfModes);
        end

        frequencyBR(iRun, :) = result.freqHz;
    end

    writematrix( ...
        [(1:numberOfRuns).', frequencyBR], ...
        brFrequencyCacheFile);
end

%% -------------------- HANNOVER OBSERVATIONS --------------------
hannoverResults = readmatrix(hannoverMeasurementsFile);

if size(hannoverResults, 1) ~= numberOfRuns || ...
        size(hannoverResults, 2) < 1 + numberOfModes
    error("Expected a 100-row Hannover file with run ID and four modes.");
end

runIDDE = hannoverResults(:, 1);
frequencyDE = hannoverResults(:, 2:(1 + numberOfModes));

if any(runIDDE ~= (1:numberOfRuns).')
    warning("Hannover run IDs are not the expected sequence 1:100.");
end

%% -------------------- SUMMARY EXPORTS --------------------
mode = (1:numberOfModes).';
meanBRHz = mean(frequencyBR, 1, "omitnan").';
stdBRHz = std(frequencyBR, 0, 1, "omitnan").';
countBR = sum(isfinite(frequencyBR), 1).';
meanDEHz = mean(frequencyDE, 1, "omitnan").';
stdDEHz = std(frequencyDE, 0, 1, "omitnan").';
countDE = sum(isfinite(frequencyDE), 1).';

statistics = table( ...
    mode, ...
    meanBRHz, ...
    stdBRHz, ...
    countBR, ...
    meanDEHz, ...
    stdDEHz, ...
    countDE, ...
    VariableNames=[ ...
        "Mode", ...
        "MeanBR_Hz", ...
        "StdBR_Hz", ...
        "CountBR", ...
        "MeanDE_Hz", ...
        "StdDE_Hz", ...
        "CountDE"]);

writetable(statistics, fullfile( ...
    outputFolder, "BR_DE_frequency_statistics.csv"));
writematrix( ...
    [(1:numberOfRuns).', frequencyBR], ...
    brFrequencyCacheFile);
writematrix( ...
    [runIDDE, frequencyDE], ...
    fullfile(outputFolder, "DE_frequencies_porto_style.csv"));

%% -------------------- PAIRWISE CROSS-SCATTER PLOTS --------------------
colorBR = [0.0000, 0.4470, 0.7410];
colorDE = [0.8500, 0.3250, 0.0980];
modePairs = nchoosek(1:numberOfModes, 2);

crossFigure = figure( ...
    "Name", "BR-DE modal-frequency cross scatter", ...
    "Color", "w", ...
    "Position", [100, 100, 1500, 820]);
layout = tiledlayout(2, 3, ...
    "TileSpacing", "compact", ...
    "Padding", "compact");

legendHandles = gobjects(4, 1);

for iPair = 1:size(modePairs, 1)
    iMode = modePairs(iPair, 1);
    jMode = modePairs(iPair, 2);
    axesHandle = nexttile;
    hold(axesHandle, "on");

    validBR = isfinite(frequencyBR(:, iMode)) & ...
        isfinite(frequencyBR(:, jMode));
    validDE = isfinite(frequencyDE(:, iMode)) & ...
        isfinite(frequencyDE(:, jMode));

    scatterBR = scatter( ...
        axesHandle, ...
        frequencyBR(validBR, iMode), ...
        frequencyBR(validBR, jMode), ...
        24, ...
        colorBR, ...
        "o", ...
        "filled", ...
        "MarkerFaceAlpha", 0.45, ...
        "MarkerEdgeAlpha", 0.65);
    scatterDE = scatter( ...
        axesHandle, ...
        frequencyDE(validDE, iMode), ...
        frequencyDE(validDE, jMode), ...
        24, ...
        colorDE, ...
        "o", ...
        "filled", ...
        "MarkerFaceAlpha", 0.45, ...
        "MarkerEdgeAlpha", 0.65);

    meanBR = mean(frequencyBR(validBR, [iMode, jMode]), 1);
    meanDE = mean(frequencyDE(validDE, [iMode, jMode]), 1);
    meanMarkerBR = plot( ...
        axesHandle, ...
        meanBR(1), ...
        meanBR(2), ...
        "p", ...
        "Color", colorBR, ...
        "MarkerFaceColor", "w", ...
        "MarkerSize", 12, ...
        "LineWidth", 1.8);
    meanMarkerDE = plot( ...
        axesHandle, ...
        meanDE(1), ...
        meanDE(2), ...
        "p", ...
        "Color", colorDE, ...
        "MarkerFaceColor", "w", ...
        "MarkerSize", 12, ...
        "LineWidth", 1.8);

    plotCovarianceEllipse( ...
        axesHandle, ...
        frequencyBR(validBR, [iMode, jMode]), ...
        colorBR, ...
        0.95);
    plotCovarianceEllipse( ...
        axesHandle, ...
        frequencyDE(validDE, [iMode, jMode]), ...
        colorDE, ...
        0.95);

    grid(axesHandle, "on");
    box(axesHandle, "on");
    xlabel(axesHandle, sprintf("$f_%d$ [Hz]", iMode), ...
        "Interpreter", "latex");
    ylabel(axesHandle, sprintf("$f_%d$ [Hz]", jMode), ...
        "Interpreter", "latex");
    title(axesHandle, sprintf("Modes %d and %d", iMode, jMode));

    xlim(axesHandle, paddedLimits([ ...
        frequencyBR(validBR, iMode); ...
        frequencyDE(validDE, iMode)]));
    ylim(axesHandle, paddedLimits([ ...
        frequencyBR(validBR, jMode); ...
        frequencyDE(validDE, jMode)]));

    if iPair == 1
        legendHandles = [ ...
            scatterBR; ...
            scatterDE; ...
            meanMarkerBR; ...
            meanMarkerDE];
    end
end

title(layout, ...
    "Modal-frequency cross scatter: Porto Alegre (BR) vs Hannover (DE)");
legendHandle = legend( ...
    legendHandles, ...
    {"BR observations", "DE observations", "BR mean", "DE mean"}, ...
    "Orientation", "horizontal");
legendHandle.Layout.Tile = "south";

pngPath = fullfile( ...
    outputFolder, "BR_DE_frequency_cross_scatter.png");
pdfPath = fullfile( ...
    outputFolder, "BR_DE_frequency_cross_scatter.pdf");
exportgraphics(crossFigure, pngPath, "Resolution", 300);
exportgraphics(crossFigure, pdfPath, "ContentType", "vector");

fprintf("\nCampaign frequency statistics:\n");
disp(statistics);
fprintf("Cross-scatter plots saved to:\n  %s\n  %s\n", ...
    pngPath, pdfPath);

%% -------------------- LOCAL FUNCTIONS --------------------
function limits = paddedLimits(values)
values = values(isfinite(values));

if isempty(values)
    limits = [0, 1];
    return;
end

minimumValue = min(values);
maximumValue = max(values);
valueRange = maximumValue - minimumValue;

if valueRange <= 0
    valueRange = max(abs(minimumValue), 1) * 0.1;
end

padding = 0.08 * valueRange;
limits = [minimumValue - padding, maximumValue + padding];
end

function plotCovarianceEllipse(axesHandle, observations, color, probability)
if size(observations, 1) < 3 || any(~isfinite(observations), "all")
    return;
end

center = mean(observations, 1).';
covarianceMatrix = cov(observations);
[eigenvectors, eigenvalues] = eig( ...
    covarianceMatrix, ...
    "vector");
eigenvalues = max(real(eigenvalues), 0);
radius = sqrt(-2 * log(1 - probability));
angle = linspace(0, 2 * pi, 240);
unitCircle = [cos(angle); sin(angle)];
ellipse = center + ...
    radius * eigenvectors * diag(sqrt(eigenvalues)) * unitCircle;

plot( ...
    axesHandle, ...
    ellipse(1, :), ...
    ellipse(2, :), ...
    "-", ...
    "Color", color, ...
    "LineWidth", 1.5, ...
    "HandleVisibility", "off");
end
